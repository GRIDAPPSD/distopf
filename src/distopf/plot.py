def _get_id_name_cols(df: pd.DataFrame) -> tuple[str, str]:
    """Return the (id_col, name_col) pair present in df.

    Supports both bus-indexed DataFrames (id, name) and
    branch-indexed DataFrames (tb, to_name).
    """
    if "tb" in df.columns:
        return "tb", "to_name" if "to_name" in df.columns else "tb"
    return "id", "name"


def _choose_t(df, t=None):
    df = df.copy()
    if "t" in df.columns:
        if t is None and len(df) > 0:
            t = min(df.t)
        df = df.loc[df.t == t, :]
        df = df.drop("t", axis=1)
    return df


def _remove_empty_triplex_phases(df: pd.DataFrame) -> pd.DataFrame:
    """Remove s1 and s2 columns if they contain only NaNs or 0s.

    Parameters
    ----------
    df : pd.DataFrame
        DataFrame to clean

    Returns
    -------
    pd.DataFrame
        DataFrame with empty triplex columns removed
    """
    df = df.copy()
    for col in ["s1", "s2"]:
        if col in df.columns:
            col_data = df[col].dropna()
            if len(col_data) == 0 or (col_data == 0).all():
                df = df.drop(columns=[col])
    return df


def plot_schedules(schedules: pd.DataFrame) -> go.Figure:
    """
    Plot time-series schedules as faceted line plots.

    Each column (except 'time') is plotted as a separate facet row with
    its own independent y-axis scale. Variables are differentiated by color
    with y-axis titles showing the variable name.

    Parameters
    ----------
    schedules : pd.DataFrame
        DataFrame with a 'time' column and arbitrary number of schedule columns

    Returns
    -------
    fig : Plotly figure object
        Faceted line plot with one row per schedule variable
    """
    df = schedules.copy()
    variables = [col for col in df.columns if col != "time"]

    df_melted = df.melt(id_vars="time")

    fig = px.line(
        df_melted, x="time", y="value", facet_row="variable", color="variable"
    )

    # Hide legend and remove facet annotations
    fig.update_layout(showlegend=False)
    fig.for_each_annotation(lambda a: a.update(text=""))

    # Make y-axes independent and set titles
    # Reverse the order to match facet row ordering
    for i, variable in enumerate(reversed(variables), 1):
        fig.update_yaxes(title_text=variable, matches=None, row=i, col=1)

    return fig


def plot_voltages(v: pd.DataFrame, t=None) -> go.Figure:
    """
    Parameters
    ----------
    v : pd.DataFrame, Dataframe containing solved voltages for each bus.
        Typically generated by the LinDistModel.get_voltages() method.
    t : int or None
        Time step to plot. If None and v contains multiple time steps,
        creates an animated figure with a slider.

    Returns
    -------
    fig : Plotly figure object
        Plotly figure object containing the voltage magnitudes for each bus.
        If multiple time steps are present and t is None, returns an animated figure.
    """
    v = _remove_empty_triplex_phases(v)

    v = v.copy()
    if "id" not in v.columns:
        v["id"] = v.index
    if "name" not in v.columns:
        v["name"] = v["id"]

    # Check if we should create animation
    animate = t is None and "t" in v.columns and len(v.t.unique()) > 1

    if not animate:
        v = _choose_t(v, t=t)
        v = v.melt(
            ignore_index=False, id_vars=["id", "name"], var_name="phase", value_name="v"
        )
        v["v"] = v["v"].astype(float)
        fig = px.scatter(v, x=v.name, y="v", facet_col="phase", color="phase")
    else:
        v = v.melt(
            ignore_index=False,
            id_vars=["id", "name", "t"],
            var_name="phase",
            value_name="v",
        )
        v["v"] = v["v"].astype(float)
        fig = px.scatter(
            v, x=v.name, y="v", facet_col="phase", color="phase", animation_frame="t"
        )

    fig.for_each_annotation(lambda a: a.update(text=a.text.split("=")[-1].upper()))
    fig.for_each_xaxis(lambda a: a.update(title="Bus Name"))
    return fig


def compare_voltages(v1: pd.DataFrame, v2: pd.DataFrame, t=None) -> go.Figure:
    """
    Visually compare voltages by plotting two different results.
    Parameters
    ----------
    v1 : pd.DataFrame
    v2 : pd.DataFrame

    Returns
    -------
    fig : Plotly figure object
    """
    v1 = _remove_empty_triplex_phases(v1)
    v2 = _remove_empty_triplex_phases(v2)
    v1 = v1.copy()
    v2 = v2.copy()
    if "id" not in v1.columns:
        v1["id"] = v1.index
    if "name" not in v1.columns:
        v1["name"] = v1["id"]
    if "id" not in v2.columns:
        v2["id"] = v2.index
    if "name" not in v2.columns:
        v2["name"] = v2["id"]
    t1 = t2 = t
    if t is None and "t" in v1.columns:
        t1 = min(v1.t)
    if t is None and "t" in v2.columns:
        t2 = min(v2.t)
    if "t" in v1.columns and "t" in v2.columns:
        assert t1 == t2
    if "t" in v1.columns:
        v1 = pd.DataFrame(v1.loc[v1.t == t1, :])
        v1 = v1.drop("t", axis=1)
    if "t" in v2.columns:
        v2 = pd.DataFrame(v2.loc[v2.t == t2, :])
        v2 = v2.drop("t", axis=1)
    v1 = v1.melt(
        ignore_index=True, var_name="phase", id_vars=["id", "name"], value_name="v1"
    )
    v2 = v2.melt(
        ignore_index=True, var_name="phase", id_vars=["id", "name"], value_name="v2"
    )
    v = pd.merge(v1, v2, on=["id", "name", "phase"])
    v = v.melt(
        ignore_index=True,
        var_name="value",
        id_vars=["id", "name", "phase"],
        value_name="v",
    ).sort_values(by=["id", "phase"])
    # v1["v1"] = v1["v1"].astype(float)
    # v2["v2"] = v2["v2"].astype(float)
    # v = pd.merge(v1, v2, on=["name", "phase"])
    fig = px.line(v, x="name", facet_col="phase", y="v", color="value", markers=True)
    fig.for_each_annotation(lambda a: a.update(text=a.text.split("=")[-1].upper()))
    fig.for_each_xaxis(lambda a: a.update(title="Bus Name"))
    return fig


