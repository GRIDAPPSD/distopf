def plot_gens(p_gens: pd.DataFrame, q_gens: pd.DataFrame, t=None) -> go.Figure:
    """
    Plot the active and reactive power flowing into each bus on each phase.
    Parameters
    ----------
    p_gens : pd.DataFrame
    q_gens : pd.DataFrame
    t : int or None
        Time step to plot. If None and gens contain multiple time steps,
        creates an animated figure with a slider.
    Returns
    -------
    fig : Plotly figure object
    """
    p_gens = _remove_empty_triplex_phases(p_gens)
    q_gens = _remove_empty_triplex_phases(q_gens)

    p_gens = p_gens.copy()
    q_gens = q_gens.copy()

    # Check if we should create animation
    animate = t is None and "t" in p_gens.columns and len(p_gens.t.unique()) > 1

    if not animate:
        p_gens = _choose_t(p_gens, t=t)
        q_gens = _choose_t(q_gens, t=t)

    animation_frame = None
    id_vars_p = ["id", "name"]
    id_vars_gens = ["id", "name", "phase"]
    if animate:
        id_vars_p = ["id", "name", "t"]
        id_vars_gens = ["id", "name", "phase", "t"]
        animation_frame = "t"

    p_gens = p_gens.melt(
        ignore_index=True,
        id_vars=id_vars_p,
        var_name="phase",
        value_name="P",
    )
    q_gens = q_gens.melt(
        ignore_index=True,
        id_vars=id_vars_p,
        var_name="phase",
        value_name="Q",
    )
    gens = pd.merge(
        p_gens,
        q_gens,
        how="outer",
        on=["id", "name", "phase"] + (["t"] if animate else []),
    )
    gens.id = p_gens.id
    gens.name = p_gens.name
    gens.phase = p_gens.phase
    if animate:
        gens["t"] = p_gens["t"]
    gens["P"] = p_gens["P"]
    gens["Q"] = q_gens["Q"]
    gens = gens.melt(
        ignore_index=False,
        id_vars=id_vars_gens,
        var_name="part",
        value_name="power",
    )
    fig = px.bar(
        gens,
        x="name",
        y="power",
        facet_col="phase",
        facet_row="part",
        color="phase",
        labels={"name": "Bus Name"},
        animation_frame=animation_frame,
    )
    fig.for_each_annotation(lambda a: a.update(text=a.text.split("=")[-1].upper()))
    fig.update_yaxes(title_text="Active Power (p.u.)", row=2, col=1)
    fig.update_yaxes(title_text="Reactive Power (p.u.)", row=1, col=1)
    return fig


def plot_pq(p: pd.DataFrame, q: pd.DataFrame, t=None) -> go.Figure:
    """
    Plot the active and reactive power.
    Parameters
    ----------
    p : pd.DataFrame
    q : pd.DataFrame
    t : int or None
        Time step to plot. If None and power contain multiple time steps,
        creates an animated figure with a slider.
    Returns
    -------
    fig : Plotly figure object
    """
    p = _remove_empty_triplex_phases(p)
    q = _remove_empty_triplex_phases(q)

    p = p.copy()
    q = q.copy()

    # Check if we should create animation
    animate = t is None and "t" in p.columns and len(p.t.unique()) > 1

    if not animate:
        if t is None:
            t = 0
        if "t" in p.columns:
            t1 = t
            if t is None and len(p) > 0:
                t1 = min(p.t)
            p = pd.DataFrame(p.loc[p.t == t1, :])
            p = p.drop("t", axis=1)
        if "t" in q.columns:
            t2 = t
            if t is None and len(q) > 0:
                t2 = min(q.t)
            q = pd.DataFrame(q.loc[q.t == t2, :])
            q = q.drop("t", axis=1)

    id_col, name_col = _get_id_name_cols(p)
    keep = [id_col, name_col] + [c for c in ("a", "b", "c") if c in p.columns]
    p = p[keep]
    q = q[[id_col, name_col] + [c for c in ("a", "b", "c") if c in q.columns]]

    animation_frame = None
    id_vars = [id_col, name_col]
    id_vars_final = [id_col, name_col, "phase"]
    if animate:
        id_vars = [id_col, name_col, "t"]
        id_vars_final = [id_col, name_col, "phase", "t"]
        animation_frame = "t"

    p = p.melt(
        ignore_index=True,
        id_vars=id_vars,
        var_name="phase",
        value_name="P",
    )
    q = q.melt(
        ignore_index=True,
        id_vars=id_vars,
        var_name="phase",
        value_name="Q",
    )
    merge_cols = [id_col, name_col, "phase"] + (["t"] if animate else [])
    pq = pd.merge(p, q, how="outer", on=merge_cols)
    pq[id_col] = p[id_col]
    pq[name_col] = p[name_col]
    pq.phase = p.phase
    if animate:
        pq["t"] = p["t"]
    pq["P"] = p["P"]
    pq["Q"] = q["Q"]
    pq = pq.melt(
        ignore_index=False,
        id_vars=id_vars_final,
        var_name="part",
        value_name="power",
    )
    fig = px.bar(
        pq,
        x=name_col,
        y="power",
        facet_col="phase",
        facet_row="part",
        color="phase",
        labels={name_col: "Bus Name"},
        animation_frame=animation_frame,
    )
    fig.for_each_annotation(lambda a: a.update(text=a.text.split("=")[-1].upper()))
    fig.update_layout(
        yaxis4_title="Active Power (p.u.)",
        yaxis_title="Reactive Power (p.u.)",
    )
    return fig


def compare_flows(s1: pd.DataFrame, s2: pd.DataFrame) -> go.Figure:
    """
    Similar to plot_power_flows but plots two results side by side.
    Parameters
    ----------
    s1 : pd.DataFrame
    s2 : pd.DataFrame

    Returns
    -------
    fig : Plotly figure object
    """
    s1 = _remove_empty_triplex_phases(s1)
    s2 = _remove_empty_triplex_phases(s2)
    s1 = s1.copy()
    s2 = s2.copy()
    if "from_name" not in s1.columns:
        s1["from_name"] = s1.fb
    if "to_name" not in s1.columns:
        s1["to_name"] = s1.tb
    if "from_name" not in s2.columns:
        s2["from_name"] = s2.fb
    if "to_name" not in s2.columns:
        s2["to_name"] = s2.tb

    s1 = s1.melt(
        ignore_index=True,
        id_vars=["fb", "tb", "from_name", "to_name"],
        var_name="phase",
        value_name="s",
    )
    s1["p"] = s1.s.apply(np.real)
    s1["q"] = s1.s.apply(np.imag)
    del s1["s"]
    s1 = s1.melt(
        ignore_index=True,
        id_vars=["fb", "tb", "from_name", "to_name", "phase"],
        var_name="part",
        value_name="s1",
    )
    s2 = s2.melt(
        ignore_index=True,
        id_vars=["fb", "tb", "from_name", "to_name"],
        var_name="phase",
        value_name="s",
    )
    s2["p"] = s2.s.apply(np.real)
    s2["q"] = s2.s.apply(np.imag)
    del s2["s"]
    s2 = s2.melt(
        ignore_index=True,
        id_vars=["fb", "tb", "from_name", "to_name", "phase"],
        var_name="part",
        value_name="s2",
    )
    s = pd.merge(
        s1, s2, on=["fb", "tb", "from_name", "to_name", "phase", "part"], how="outer"
    )
    fig = px.bar(
        s,
        x="to_name",
        y=["s1", "s2"],
        facet_col="phase",
        facet_row="part",
        barmode="group",
        labels={"to_name": "To-Bus Name"},
    )
    fig.for_each_annotation(lambda a: a.update(text=a.text.split("=")[-1].upper()))
    fig.update_layout(
        yaxis4_title="Active Power (p.u.)",
        yaxis_title="Reactive Power (p.u.)",
    )
    return fig


